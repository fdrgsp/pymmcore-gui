    bg_active=Color(0x40, 0x40, 0x40),
    text_primary=Color(0xE0, 0xE0, 0xE0),
    text_secondary=Color(0xA0, 0xA0, 0xA0),
    text_disabled=Color(0x70, 0x70, 0x70),
    border_subtle=Color(0x33, 0x33, 0x33),
